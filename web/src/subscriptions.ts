export function subscriptionMessage(
  code: string,
  t: (zh: string, en: string) => string,
) {
  const text = messages[code];
  return text ? t(...text) : code;
}
export function nodeKey(node: SubscriptionNode) {
  return JSON.stringify([node.server_id, node.tag]);
}
export function nodeMember(node: SubscriptionNode): SubscriptionMember {
  return { kind: "node", server_id: node.server_id, tag: node.tag };
}
export function memberKey(member: SubscriptionMember) {
  if (member.kind === "node")
    return `node:${nodeKey({ server_id: member.server_id || "", tag: member.tag || "" })}`;
  return member.kind === "group" ? `group:${member.group_id}` : "direct";
}
export interface SubscriptionNodeRow extends SubscriptionNode {
  key: string;
  name: string;
  type: string;
  address: string;
  port: number;
  server_name: string;
  issue?: string;
}
export function subscriptionNodeRows(
  sources: SubscriptionSource[],
): SubscriptionNodeRow[] {
  return sources.flatMap((source) =>
    source.nodes.map((node, index) => ({
      server_id: source.id,
      tag: node.tag,
      key: `${source.id}:${index}`,
      name: `${source.name} · ${node.tag || node.type}`,
      type: node.type,
      address: source.address,
      port: node.port,
      server_name: node.server_name,
      issue: source.issue || node.issue,
    })),
  );
}
export function selectedSubscriptionNodes(
  profile: Subscription,
  sources: SubscriptionSource[],
) {
  if (profile.scope === "nodes") return profile.nodes;
  return subscriptionNodeRows(sources)
    .filter(
      (node) =>
        node.tag &&
        !node.issue &&
        (profile.scope === "all" || profile.servers.includes(node.server_id)),
    )
    .map(({ server_id, tag }) => ({ server_id, tag }));
}
export function editableSubscription(
  initial: Subscription,
  sources: SubscriptionSource[],
): Subscription {
  const profile = structuredClone(initial);
  const nodes = selectedSubscriptionNodes(profile, sources);
  const legacyDirects = profile.groups.filter(
    (group) => group.type === "direct",
  );
  const firstDirect = !profile.direct ? legacyDirects[0] : undefined;
  const direct = profile.direct || {
    enabled: !!firstDirect,
    tag: firstDirect?.tag || "direct",
  };
  const groups = profile.groups
    .filter((group) => group !== firstDirect)
    .map((group) => ({ ...group, id: group.id || newID() }));
  const nodeMembers = nodes.map(nodeMember);
  return {
    ...profile,
    scope: "nodes",
    servers: [],
    nodes,
    direct,
    groups: groups.map((group): SubscriptionGroup => {
      if (group.type === "direct")
        return { ...group, type: "selector", members: [{ kind: "direct" }] };
      if (Array.isArray(group.members)) return group;
      const members: SubscriptionMember[] =
        group.type === "urltest"
          ? [...nodeMembers]
          : [
              ...groups
                .filter(
                  (item) => item.type === "urltest" || item.type === "direct",
                )
                .map((item): SubscriptionMember => ({
                  kind: "group",
                  group_id: item.id,
                })),
              ...(direct.enabled
                ? [{ kind: "direct" } as SubscriptionMember]
                : []),
              ...nodeMembers,
            ];
      return { ...group, members };
    }),
  };
}
export function selectSubscriptionNodes(
  profile: Subscription,
  nodes: SubscriptionNode[],
  enabled = profile.direct?.enabled || false,
): Partial<Subscription> {
  const keys = new Set(nodes.map(nodeKey));
  return {
    nodes,
    direct: { tag: profile.direct?.tag ?? "direct", enabled },
    groups: profile.groups.map((group) => ({
      ...group,
      members: (group.members || []).filter((member) => {
        if (member.kind === "direct") return enabled;
        if (member.kind !== "node") return true;
        return keys.has(
          nodeKey({ server_id: member.server_id || "", tag: member.tag || "" }),
        );
      }),
    })),
  };
}
export function groupWouldCycle(
  groups: SubscriptionGroup[],
  groupID: string,
  targetID: string,
) {
  const seen = new Set<string>();
  function reaches(id: string): boolean {
    if (id === groupID) return true;
    if (seen.has(id)) return false;
    seen.add(id);
    return (groups.find((group) => group.id === id)?.members || []).some(
      (member) => member.kind === "group" && reaches(member.group_id || ""),
    );
  }
  return reaches(targetID);
}
export function subscriptionURL(profile: Subscription) {
  return `${panelOrigin()}/subscribe/${encodeURIComponent(profile.id)}/${encodeURIComponent(profile.token)}`;
}
export async function generateSubscription(
  profile: Subscription,
  signal?: AbortSignal,
) {
  const result = await api<SubscriptionResult>("/subscriptions/preview", {
    method: "POST",
    json: { ...profile, name: profile.name.trim() || "preview" },
    signal,
  });
  if (!result.content || result.error) return result;
  const schema = await loadTemplateSchema();
  if (signal?.aborted) throw new DOMException("Aborted", "AbortError");
  const errors = inspectConfig(parseConfig(result.content), schema).filter(
    (issue) => issue.severity === "error",
  );
  if (errors.length)
    return { ...result, content: undefined, validation_errors: errors };
  return result;
}
